# Подключаем модуль math
import math

# Получаем радиус от пользователя и превращаем в число
R = float(input("Введите радиус: "))

# Считаем длину окружности (C = 2 * pi * R)
length = 2 * math.pi * R

# Считаем площадь круга (S = pi * R^2)
area = math.pi * R * R

# Выводим результат
print("Длина окружности:", length)
print("Площадь круга:", area)
